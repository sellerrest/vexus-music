import axios from 'axios'

/**
 * Адрес сервера.
 *
 * В браузере приложение лежит на том же домене, что и API, поэтому база
 * пустая и все запросы остаются относительными — так было и работает.
 *
 * В упакованных сборках (.exe и .apk) страница открывается уже не с нашего
 * домена, а из самого приложения: в Electron это file://, в Android WebView —
 * https://localhost. Относительный /api/home там указывал бы внутрь пакета,
 * где никакого сервера нет. Поэтому при сборке приложения подставляется
 * полный адрес через VITE_API_BASE, и запросы уходят на боевой сервер.
 *
 * Кросс-доменные запросы разрешены: у API стоит allow_origins=["*"], а токен
 * ездит в заголовке Authorization, не в куках, — значит origin ни на что не
 * влияет и ослаблять ничего не пришлось.
 */
export const API_BASE: string = (import.meta.env.VITE_API_BASE as string | undefined) || ''

// Одной строкой на все 37 мест, где вызывается axios: каждое из них ходит по
// относительному пути, и подменять их по одному значило бы рано или поздно
// пропустить какое-то.
axios.defaults.baseURL = API_BASE

/**
 * Дополняет ссылку адресом сервера, если она относительная.
 *
 * Нужна для картинок: они грузятся тегом <img>, минуя axios. Большинство
 * обложек приходят абсолютными ссылками на CDN и остаются как есть, но у
 * трека без готовой обложки сервер отдаёт /api/cover/<id> — вот его и надо
 * достроить.
 */
export function apiUrl(path: string | null): string | null {
  if (!path || !path.startsWith('/')) return path
  return API_BASE + path
}
