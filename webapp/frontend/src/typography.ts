/**
 * Русская типографика для текста интерфейса.
 *
 * Правила, которые тут выполняются:
 *
 * 1. Кавычки — «ёлочки», вложенные — „лапки“. Прямые " и ' остаются только
 *    в коде, в тексте их быть не должно.
 * 2. Тире и дефис — разные знаки. Дефис (-) склеивает слова внутри («интернет-
 *    магазин»), среднее тире (–) обозначает диапазон («10–15 минут»), длинное
 *    тире (—) разделяет мысли в предложении.
 * 3. Неразрывный пробел после коротких предлогов и союзов: предлог не должен
 *    оставаться висеть в конце строки в отрыве от своего слова. То же перед
 *    длинным тире — оно не должно начинать строку.
 *
 * Висячая пунктуация (кавычка на краю выносится в поле) делается не тут, а в
 * стилях: hanging-punctuation на body.
 *
 * Функция идемпотентна: повторный прогон уже обработанной строки ничего не
 * меняет — иначе при перерисовке списка текст «плыл» бы от прогона к прогону.
 */

const NBSP = ' '
const EN_DASH = '–'
const EM_DASH = '—'

/**
 * Предлоги, союзы и частицы, которые нельзя отрывать от следующего слова.
 * Однобуквенные — все; из длинных взяты самые частые в интерфейсе.
 */
const SHORT_WORDS =
  'а|в|и|к|о|с|у|я|не|ни|но|из|от|до|за|на|по|во|со|ко|для|при|про|над|под|без|что|как|уже|или|это|все|ещё|еще'

// Слева от предлога — начало строки или что угодно, кроме буквы и дефиса:
// иначе «по» внутри «поиск» сошло бы за предлог. Проверяющий символ входит в
// совпадение и потому съедается — из-за этого два коротких слова подряд («а
// не только») за один проход не обработать, и замена гоняется до стабильного
// состояния (см. ниже). Ретроспективная проверка (?<!…) решила бы это в один
// проход, но её не понимают Safari до 16.4: там ломался бы не текст, а вся
// сборка целиком — регулярка разбирается при загрузке файла.
const PREPOSITION = new RegExp(`(^|[^А-Яа-яЁёA-Za-z-])(${SHORT_WORDS}) +`, 'gi')

/** Символы, после которых прямая кавычка — открывающая, а не закрывающая. */
const BEFORE_OPENING = /[\s(\[{«„—–-]/

/**
 * Прямые кавычки — в «ёлочки», вложенные — в „лапки“.
 *
 * По самому символу " не понять, открывает он или закрывает, поэтому идём по
 * строке и смотрим на соседа слева: после пробела или открывающей скобки —
 * открываем, после буквы или знака — закрываем. Одиночная ' не трогается
 * вовсе: в английских названиях это апостроф (don't, rock'n'roll).
 */
function quotes(input: string): string {
  let depth = 0
  return input.replace(/"/g, (_match, offset: number, whole: string) => {
    const prev = whole[offset - 1]
    if (prev === undefined || BEFORE_OPENING.test(prev)) {
      depth += 1
      return depth > 1 ? '„' : '«'
    }
    const nested = depth > 1
    depth = Math.max(0, depth - 1)
    return nested ? '“' : '»'
  })
}

export function typo(input: string): string {
  let s = quotes(input)

  // --- Тире ------------------------------------------------------------
  // Дефис в окружении пробелов — это всегда длинное тире, а не дефис.
  s = s.replace(/ +- +/g, ` ${EM_DASH} `)
  // Диапазон между числами — среднее тире, без пробелов.
  s = s.replace(/(\d) *- *(\d)/g, `$1${EN_DASH}$2`)

  // --- Неразрывные пробелы ---------------------------------------------
  // Тире не должно начинать строку: приклеиваем его к предыдущему слову.
  s = s.replace(new RegExp(` +${EM_DASH}`, 'g'), `${NBSP}${EM_DASH}`)
  // Число не отрывается от того, что считает: «5 треков», «12 мин».
  s = s.replace(/(\d) +(?=[А-Яа-яЁёA-Za-z])/g, `$1${NBSP}`)
  // Предлог уезжает вместе со своим словом. Проходов ровно столько, сколько
  // нужно, чтобы строка перестала меняться: цепочки вроде «а не только»
  // обрабатываются по одному слову за проход. Ограничение сверху — защита от
  // бесконечного цикла, если правило когда-нибудь станет незавершающимся.
  for (let pass = 0; pass < 8; pass++) {
    const next = s.replace(PREPOSITION, `$1$2${NBSP}`)
    if (next === s) break
    s = next
  }

  return s
}
