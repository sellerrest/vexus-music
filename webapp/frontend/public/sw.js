/*
 * Минимальный сервис-воркер.
 *
 * Нужен ровно для одного: без него браузер не считает сайт устанавливаемым и
 * не предлагает добавить его на главный экран. Кэшированием он намеренно НЕ
 * занимается — приложение целиком зависит от сервера (музыка, подборки,
 * авторизация), а частично закэшированная версия вела бы себя непредсказуемо
 * и залипала бы на старой сборке после выкладки.
 */

self.addEventListener('install', () => {
  // Не ждём закрытия старых вкладок — новая версия должна вступать сразу.
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim())
})

self.addEventListener('fetch', (event) => {
  // Обработчик обязателен для установки, но ничего не подменяет: запрос
  // уходит в сеть как обычно.
  event.respondWith(fetch(event.request))
})
